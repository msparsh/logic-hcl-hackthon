-- =====================================================================
-- Team Logic — Autonomous Customer Support Agent
-- PostgreSQL schema (Neon / PostgreSQL 15+)
-- Rule IDs (R1–R12) refer to docs/BUSINESS_RULES.md
--
-- Two schemas:
--   raw  : Kaggle CSVs loaded as-is (never edited by the app)
--   app  : clean tables the agent reads and writes
--
-- ASSUMPTION: Kaggle column names below must be checked against the
-- downloaded files before loading (customer.csv, product.csv,
-- transactions.csv, click_stream.csv).
-- =====================================================================

CREATE SCHEMA IF NOT EXISTS raw;
CREATE SCHEMA IF NOT EXISTS app;

-- ---------------------------------------------------------------------
-- RAW (staging) — loaded by data/load_data.py with pandas, all TEXT
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS raw.customer (
    customer_id        TEXT,
    first_name         TEXT,
    last_name          TEXT,
    username           TEXT,
    email              TEXT,
    gender             TEXT,
    birthdate          TEXT,
    home_location      TEXT,
    home_country       TEXT,
    first_join_date    TEXT
);

CREATE TABLE IF NOT EXISTS raw.product (
    id                 TEXT,
    product_display_name TEXT,
    master_category    TEXT,
    sub_category       TEXT,
    article_type       TEXT,
    base_colour        TEXT
);

CREATE TABLE IF NOT EXISTS raw.transactions (
    created_at             TEXT,
    customer_id            TEXT,
    booking_id             TEXT,
    session_id             TEXT,
    product_metadata       TEXT,   -- list of {product_id, quantity, item_price}
    payment_method         TEXT,
    payment_status         TEXT,
    promo_amount           TEXT,
    promo_code             TEXT,
    shipment_fee           TEXT,
    shipment_date_limit    TEXT,
    shipment_location_lat  TEXT,
    shipment_location_long TEXT,
    total_amount           TEXT
);
-- click_stream.csv is not loaded: browsing events are out of scope.

-- ---------------------------------------------------------------------
-- APP — customers
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS app.customers (
    customer_id     BIGINT PRIMARY KEY,
    first_name      TEXT NOT NULL,
    last_name       TEXT,
    email           TEXT NOT NULL UNIQUE,
    home_location   TEXT,
    home_country    TEXT,
    pin_hash        TEXT NOT NULL,              -- bcrypt hash of demo PIN
    joined_at       DATE
);

-- ---------------------------------------------------------------------
-- APP — products (to show what is inside an order)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS app.products (
    product_id      BIGINT PRIMARY KEY,
    name            TEXT NOT NULL,
    category        TEXT,
    sub_category    TEXT,
    article_type    TEXT,
    base_colour     TEXT
);

-- ---------------------------------------------------------------------
-- APP — orders (the only table the agent changes)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS app.orders (
    order_id          BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 10001) PRIMARY KEY,
    order_ref         TEXT GENERATED ALWAYS AS ('ORD-' || order_id::text) STORED UNIQUE,  -- e.g. ORD-10023
    booking_id        TEXT NOT NULL UNIQUE,      -- original Kaggle ID (long)
    customer_id       BIGINT NOT NULL REFERENCES app.customers(customer_id),
    created_at        TIMESTAMPTZ NOT NULL,
    payment_method    TEXT,
    payment_status    TEXT NOT NULL CHECK (payment_status IN ('Success', 'Failed')),
    status            TEXT NOT NULL DEFAULT 'placed'
                      CHECK (status IN ('placed', 'shipped', 'delivered', 'cancelled')),
    shipping_address  TEXT NOT NULL CHECK (length(trim(shipping_address)) >= 5),
    shipping_country  TEXT NOT NULL,              -- R6: address must stay in this country
    shipping_lat      NUMERIC(9,6),
    shipping_long     NUMERIC(9,6),
    delivery_date     DATE,                       -- current delivery date (from shipment_date_limit)
    original_delivery_date DATE,                  -- R8: postpone limit is measured from this
    promo_code        TEXT,
    promo_amount      NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (promo_amount >= 0),
    shipment_fee      NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (shipment_fee >= 0),
    total_amount      NUMERIC(12,2) NOT NULL CHECK (total_amount >= 0),
    version           INTEGER NOT NULL DEFAULT 1, -- bumped on every change (conflict check)
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_orders_customer ON app.orders (customer_id);

-- ---------------------------------------------------------------------
-- APP — order_items (parsed from product_metadata)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS app.order_items (
    order_id     BIGINT NOT NULL REFERENCES app.orders(order_id) ON DELETE CASCADE,
    product_id   BIGINT NOT NULL REFERENCES app.products(product_id),
    quantity     INTEGER NOT NULL CHECK (quantity > 0),
    item_price   NUMERIC(12,2) NOT NULL CHECK (item_price >= 0),
    PRIMARY KEY (order_id, product_id)
);

-- ---------------------------------------------------------------------
-- APP — change_requests (preview -> confirm; double-booking guard)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS app.change_requests (
    request_id       UUID PRIMARY KEY,
    session_id       TEXT NOT NULL,
    customer_id      BIGINT NOT NULL REFERENCES app.customers(customer_id),
    order_id         BIGINT REFERENCES app.orders(order_id),
    intent           TEXT NOT NULL
                     CHECK (intent IN ('change_address', 'cancel_order', 'postpone_delivery',
                                       'track_order', 'general_inquiry', 'unknown')),
    confidence       NUMERIC(3,2) CHECK (confidence BETWEEN 0 AND 1),   -- R11: below 0.70 -> ask
    proposed_change  JSONB NOT NULL DEFAULT '{}'::jsonb,   -- e.g. {"shipping_address": "12 MG Road"}
    preview          JSONB,                                -- {"old": {...}, "new": {...}}
    order_version    INTEGER,                              -- orders.version seen at preview time
    status           TEXT NOT NULL DEFAULT 'pending'
                     CHECK (status IN ('pending', 'confirmed', 'declined', 'expired', 'blocked', 'applied')),
    idempotency_key  TEXT NOT NULL UNIQUE,                 -- same change can be applied only once
    expires_at       TIMESTAMPTZ NOT NULL,                 -- preview valid for 5 minutes
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    decided_at       TIMESTAMPTZ
);

-- At most ONE open (pending) change per order at a time.
CREATE UNIQUE INDEX IF NOT EXISTS uq_one_pending_change_per_order
    ON app.change_requests (order_id)
    WHERE status = 'pending';

CREATE INDEX IF NOT EXISTS idx_change_requests_customer
    ON app.change_requests (customer_id, status);

-- ---------------------------------------------------------------------
-- APP — audit_log (append-only trail of every decision)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS app.audit_log (
    audit_id      BIGSERIAL PRIMARY KEY,
    request_id    UUID REFERENCES app.change_requests(request_id),
    customer_id   BIGINT REFERENCES app.customers(customer_id),
    order_id      BIGINT REFERENCES app.orders(order_id),
    action        TEXT NOT NULL,            -- e.g. preview_shown, change_applied, blocked
    decision      TEXT NOT NULL
                  CHECK (decision IN ('approved', 'blocked', 'declined', 'failed',
                                      'needs_info', 'needs_confirmation', 'expired', 'escalated')),
    rule_results  JSONB NOT NULL DEFAULT '{}'::jsonb,   -- {"R2_ownership": {"passed": true, "reason": ""}}
    before_state  JSONB,
    after_state   JSONB,
    fallback_used BOOLEAN NOT NULL DEFAULT false,
    latency_ms    INTEGER,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_audit_order_time ON app.audit_log (order_id, created_at DESC);

-- Make audit_log append-only: block UPDATE and DELETE.
CREATE OR REPLACE FUNCTION app.block_audit_changes() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'audit_log is append-only';
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_audit_append_only ON app.audit_log;
CREATE TRIGGER trg_audit_append_only
    BEFORE UPDATE OR DELETE ON app.audit_log
    FOR EACH ROW EXECUTE FUNCTION app.block_audit_changes();

